"""
mine_coverage_metrics.py

Parses a JaCoCo XML coverage report (report.xml, generated by
`mvn jacoco:report` or `gradle jacocoTestReport`) into the Test-Coverage
metric group, per file:

    COV_instruction_pct, COV_branch_pct, COV_line_pct,
    COV_complexity_pct, COV_method_pct

Usage (CLI):
    python -m mining.mine_coverage_metrics \
        --jacoco-xml /path/to/jacoco/report.xml \
        --release v1.2 \
        --out data/raw/coverage_metrics_v1.2.csv
"""
from __future__ import annotations

import argparse
from typing import Dict

import pandas as pd
from lxml import etree

COUNTER_TYPES = ["INSTRUCTION", "BRANCH", "LINE", "COMPLEXITY", "METHOD"]


def _pct(covered: int, missed: int) -> float:
    total = covered + missed
    return round(100.0 * covered / total, 2) if total else 100.0


def parse_jacoco_report(xml_path: str) -> pd.DataFrame:
    """JaCoCo XML structure: <report><package><sourcefile name=".."><counter type=".." missed=".." covered=".."/>
    We aggregate at the sourcefile level and join package + name to build a
    file path comparable to the one used by the evolution-metrics miner."""
    # JaCoCo's report.dtd declares an external DTD reference that we don't
    # want to fetch over the network -- disable DTD loading.
    parser = etree.XMLParser(resolve_entities=False, no_network=True, load_dtd=False, dtd_validation=False)
    tree = etree.parse(xml_path, parser=parser)
    root = tree.getroot()

    rows = []
    for package in root.findall(".//package"):
        package_name = package.get("name", "")
        for sourcefile in package.findall("sourcefile"):
            file_name = sourcefile.get("name", "")
            file_path = f"{package_name}/{file_name}" if package_name else file_name
            counters: Dict[str, tuple] = {}
            for counter in sourcefile.findall("counter"):
                ctype = counter.get("type")
                missed = int(counter.get("missed", 0))
                covered = int(counter.get("covered", 0))
                counters[ctype] = (missed, covered)

            row = {"file_path": file_path}
            for ctype in COUNTER_TYPES:
                missed, covered = counters.get(ctype, (0, 0))
                row[f"COV_{ctype.lower()}_pct"] = _pct(covered, missed)
            rows.append(row)

    return pd.DataFrame(rows)


def mine_coverage_for_release(jacoco_xml_path: str, release: str) -> pd.DataFrame:
    df = parse_jacoco_report(jacoco_xml_path)
    df.insert(0, "release", release)
    return df


def main():
    parser = argparse.ArgumentParser(description="Parse a JaCoCo XML report into the Test-Coverage metric group.")
    parser.add_argument("--jacoco-xml", required=True)
    parser.add_argument("--release", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    df = mine_coverage_for_release(args.jacoco_xml, args.release)
    df.to_csv(args.out, index=False)
    print(f"Wrote {len(df)} rows to {args.out}")


if __name__ == "__main__":
    main()
